/** CLI help formatting consumes the same lower-layer declaration contracts as JSON results [C7,A1,N26]. */
import { commandDocs } from '../../../../packages/config/index.js';
export { commandDocs, declaredCommandShapes } from '../../../../packages/config/index.js';

/** Generate a browser-safe leaf; the browser never discovers files or initializes command writers. */
export function commandHelpModule(root) {
  return '/** Generated by node docs/tools/update-docs.js from apps/cli/src/io/command-docs/*.json; edit declarations. */\n'
    + `export const additionsHelp = ${JSON.stringify(commandHelpText(root))};\n`;
}

/** Build the extension section from the same source declarations used by JSON results. */
export function commandHelpText(root) {
  const text = commandDocs(root).map(entry => entry.help).join('');
  return text ? '\nAdditional commands\n' + text + '\n' : '';
}
