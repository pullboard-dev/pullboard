/** The bare flag a usage fragment starts with. */
export const flagKey = (flag) => flag.split(/\s/u, 1)[0];

/** The usage display of a flag: a value shown as <value>, "text" or a|b stays; prose that followed it is dropped. */
const CLEAN = /^--[a-z][a-z-]*(?: <[^>]+>| "[^"]*"| \S+\|\S+)?$/u;

/** The flag as a usage fragment: its value when the usage line shows one, otherwise the bare flag. */
export const cleanFlag = (scraped) => (CLEAN.test(scraped) ? scraped : flagKey(scraped));

/** One help flag line, `--flag value — meaning`, or the flag alone when no meaning is declared. */
export function describeFlag(command, scraped) {
  const key = flagKey(scraped);
  const entry = FLAG_MEANINGS[`${command} ${key}`] ?? FLAG_MEANINGS[key];
  if (entry === undefined) return scraped;
  const [display, meaning] = Array.isArray(entry) ? entry : [cleanFlag(scraped), entry];
  return `${display} — ${meaning}`;
}
