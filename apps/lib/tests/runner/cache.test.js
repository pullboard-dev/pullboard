/** A runner dispatch reuses a clean commit's source and tag scans; a refusal is never kept [C7]. */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdirSync } from 'node:fs';
import { readdirSync } from 'node:fs';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { committedRunnerController } from '../../../../packages/runners/index.js';
import { copyPackageFiles } from '../../../../packages/runners/index.js';
import { cellSandbox } from '../../../../packages/store/tests/fixtures/cell.js';
import { runFixtureChildAsync } from '../../../cli/tests/fixtures/child.js';

test('a clean commit\'s source scan and tag selection are kept per tooling tree and answered again with the same result; a refused scan keeps nothing and refuses again [C7]', async t => {
  const box = cellSandbox(t);
  const tooling = join(box.dir, 'tooling'), project = join(box.dir, 'project'), home = join(box.dir, 'home');
  for (const folder of [tooling, project, home]) mkdirSync(folder, { recursive: true });
  copyPackageFiles(resolve(import.meta.dirname, '../../../..'), tooling);
  box.git(tooling, 'init', '-q', '-b', 'main');
  box.git(tooling, 'add', '-A');
  box.git(tooling, 'commit', '-q', '-m', 'test: scanner tooling');
  const exported = committedRunnerController(tooling);
  t.after(exported.cleanup);
  writeFileSync(join(project, 'a.js'), 'export const a = 1;\n');
  box.git(project, 'init', '-q', '-b', 'main');
  box.git(project, 'add', '-A');
  box.git(project, 'commit', '-q', '-m', 'test: clean source');
  box.git(project, 'tag', 'v1');
  const clean = box.git(project, 'rev-parse', 'HEAD');
  writeFileSync(join(project, 'b.js'), `export const key = 'AKIA${'Q'.repeat(16)}';\n`);
  box.git(project, 'add', '-A');
  box.git(project, 'commit', '-q', '-m', 'test: leaked source');
  const leaked = box.git(project, 'rev-parse', 'HEAD');
  const url = file => JSON.stringify(pathToFileURL(join(exported.root, file)).href);
  const script = `import assert from 'node:assert/strict';
const { sourceObjects } = await import(${url('packages/runners/src/io/source/scan.js')});
const { candidateTags } = await import(${url('packages/runners/src/io/pack.js')});
const root = ${JSON.stringify(project)};
const first = sourceObjects(root, { commit: ${JSON.stringify(clean)} });
const tags = candidateTags(root, { commit: ${JSON.stringify(clean)} });
assert.deepEqual(tags.map(tag => tag.name), ['refs/tags/v1']);
console.log(JSON.stringify({ first, tags }));
assert.throws(() => sourceObjects(root, { commit: ${JSON.stringify(leaked)} }), { code: 'RUNNER_SECRET' });`;
  const env = { ...box.env, PULLBOARD_MACHINE_HOME: home };
  const once = await runFixtureChildAsync(process.execPath, ['--input-type=module', '-e', script], { env, encoding: 'utf8' });
  assert.equal(once.status, 0, once.context);
  const kept = readdirSync(join(home, 'source-scan'));
  assert.equal(kept.length, 2, 'one kept verdict for the clean source scan and one for its tag selection, none for the refusal');
  const again = await runFixtureChildAsync(process.execPath, ['--input-type=module', '-e', script], { env, encoding: 'utf8' });
  assert.equal(again.status, 0, again.context);
  assert.equal(again.stdout, once.stdout, 'a kept verdict answers with the same protection and tags');
  assert.deepEqual(readdirSync(join(home, 'source-scan')), kept, 'the refusal is scanned and refused again, and still keeps nothing');
});
