import { mappedPath } from '../../../logic/path/map.js';
/** Explicit falling allowances for each cells finding; report generation never writes state [C7,CD64]. */
import { CELL_METRICS } from '../lints.js';
import { Refused } from '../../../../../kernel/index.js';

/** Reject incomplete or malformed snapshots rather than silently forgiving unrecorded debt. */
export function validateCellLintBaseline(value) {
  if (value?.version !== 1 || !value.metrics || Object.keys(value.metrics).sort().join() !== [...CELL_METRICS].sort().join()) {
    throw new Refused('CELL_BASELINE', 'use an explicit complete cell lint baseline generated by this version');
  }
  for (const metric of CELL_METRICS) {
    const row = value.metrics[metric];
    if (!Number.isSafeInteger(row.count) || row.count < 0 || !row.allowances || Array.isArray(row.allowances)
      || Object.values(row.allowances).some(count => !Number.isSafeInteger(count) || count <= 0)
      || Object.values(row.allowances).reduce((sum, count) => sum + count, 0) !== row.count) {
      throw new Refused('CELL_BASELINE', `restore the complete nonnegative ${metric} baseline`);
    }
  }
}

/** Snapshot measured identities after resolving accepted renames, so same-generation snapshots remain stable. */
export function cellLintBaseline(report) {
  const map = new Map(Object.entries(report.pathMap ?? {}));
  return { version: 1, metrics: Object.fromEntries(CELL_METRICS.map(metric => {
    const allowances = Object.create(null);
    for (const finding of report.metrics[metric].findings) {
      const key = translatedAllowance(metric, finding.key, map);
      allowances[key] = (allowances[key] ?? 0) + finding.count;
    }
    return [metric, { count: report.metrics[metric].count, allowances }];
  })) };
}

/** Preserve exact committed path-map identities during an accepted move; new export names retain new debt. */
function translatedAllowance(metric, key, map) {
  if (metric === 'cycles') return key;
  if (metric === 'boundaries') return key.split('->').map(path => mappedPath(map, path)).join('->');
  if (metric === 'unreachableExports') {
    const at = key.lastIndexOf('#');
    return mappedPath(map, key.slice(0, at)) + key.slice(at);
  }
  if (metric === 'unknown') {
    const at = key.indexOf(':');
    return mappedPath(map, key.slice(0, at)) + key.slice(at);
  }
  return mappedPath(map, key);
}

/** Mark only the explicitly recorded pre-cell transition families; malformed or absent evidence stays strict. */
function transitionalGrowth(report, metric) {
  const { item, until, active } = report.transition ?? {};
  return active === true && (item === 1527 && until === 1395 || item === 1781 && until === 1770)
    && metric !== 'cycles';
}

/** Retain every rise; callers may enforce the approved transition while baseline updates always inspect all debt. */
export function cellLintGrowth(report, baseline, { enforcedOnly = false } = {}) {
  validateCellLintBaseline(baseline);
  const actual = cellLintBaseline(report);
  const growth = CELL_METRICS.flatMap(metric => {
    const before = baseline.metrics[metric], after = actual.metrics[metric];
    const map = new Map(Object.entries(report.pathMap ?? {})), allowances = new Map();
    for (const [key, count] of Object.entries(before.allowances)) {
      const target = translatedAllowance(metric, key, map);
      allowances.set(target, Math.max(allowances.get(target) ?? 0, count));
    }
    const rows = Object.entries(after.allowances).filter(([key, count]) => count > (allowances.get(key) ?? 0))
      .map(([key, count]) => ({ metric, key, actual: count, allowed: allowances.get(key) ?? 0 }));
    if (after.count > before.count) rows.push({ metric, key: '(total)', actual: after.count, allowed: before.count });
    // fileSize stores excess over 500: a per-file rise above 1000 excess crosses the hard 1500 maximum.
    return rows.map(row => transitionalGrowth(report, metric)
      && !(metric === 'fileSize' && /\.(?:[cm]?js|ts)$/u.test(row.key) && row.actual > 1000)
      ? { ...row, advisory: true, item: report.transition.item, until: report.transition.until }
      : row);
  });
  return enforcedOnly ? growth.filter(row => !row.advisory) : growth;
}

/** Compute a lower snapshot without changing the caller's baseline or accepting any increase. */
export function lowerCellLintBaseline(report, baseline) {
  const growth = cellLintGrowth(report, baseline);
  if (growth.length) throw new Refused('CELL_LINT_ROSE', `cell lint debt grew: ${growth.map(row => `${row.metric}:${row.key}`).join(', ')}; repair the increase before updating`);
  return cellLintBaseline(report);
}
