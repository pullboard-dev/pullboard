/** Landing regenerates stale shared documentation into its merge before the gate, and leaves current documentation alone [B3,C7]. */
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { readFileSync } from 'node:fs';
import { rmSync } from 'node:fs';
import { writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { amendLandingEngines } from '../../index.js';
import { cleanGitEnvironment } from '../../../git/index.js';

const IDENTITY = ['-c', 'user.name=pullboard-test', '-c', 'user.email=pullboard-test@example.invalid'];

/** Run git in a temporary repository with the landing's clean environment and fail on any refusal. */
function git(cwd, ...args) {
  const result = spawnSync('git', [...IDENTITY, ...args], { cwd, env: cleanGitEnvironment(), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  return result.stdout.trim();
}

/** Build a real temporary repository from this checkout's committed generator and documentation sources. */
function temporaryRepository() {
  const dir = mkdtempSync(join(tmpdir(), 'landing-regenerates-docs-'));
  const source = fileURLToPath(new URL('../../../../', import.meta.url));
  const archive = spawnSync('git', ['archive', 'HEAD', 'README.md', 'apps', 'docs', 'packages', 'package.json'], { cwd: source, env: cleanGitEnvironment(), maxBuffer: 512 * 1024 * 1024 });
  assert.equal(archive.status, 0, archive.stderr?.toString());
  const extracted = spawnSync('tar', ['-xf', '-', '-C', dir], { input: archive.stdout });
  assert.equal(extracted.status, 0, extracted.stderr?.toString());
  git(dir, 'init', '-q', '-b', 'main');
  git(dir, 'config', 'user.name', 'pullboard-test');
  git(dir, 'config', 'user.email', 'pullboard-test@example.invalid');
  git(dir, 'add', '-A');
  git(dir, 'commit', '-q', '-m', 'chore: fixture base');
  return dir;
}

test('a stale generated document is regenerated and amended into the merge before its gate [B3,C7]', { timeout: 120000 }, () => { // budget: one real archive extraction, one generator run and one amend.
  const dir = temporaryRepository();
  try {
    writeFileSync(join(dir, 'apps', 'cli', 'src/logic/help/additions.js'), `${readFileSync(join(dir, 'apps', 'cli', 'src/logic/help/additions.js'), 'utf8')}// stale generated documentation\n`);
    writeFileSync(join(dir, 'README.md'), `${readFileSync(join(dir, 'README.md'), 'utf8')}\nLanding fixture source change.\n`);
    git(dir, 'commit', '-q', '-am', 'docs: stale shared documentation');
    const merge = git(dir, 'rev-parse', 'HEAD');
    const parents = git(dir, 'rev-list', '--parents', '-n', '1', merge).split(' ').length;
    amendLandingEngines(dir);
    const amended = git(dir, 'rev-parse', 'HEAD');
    assert.notEqual(amended, merge, 'the stale merge is amended with regenerated bytes');
    assert.equal(git(dir, 'rev-list', '--parents', '-n', '1', amended).split(' ').length, parents, 'the amend keeps the merge parents');
    assert.ok(!git(dir, 'show', 'HEAD:apps/cli/src/logic/help/additions.js').includes('// stale generated documentation'), 'the amended commit holds regenerated documentation');
    assert.equal(git(dir, 'status', '--porcelain'), '', 'nothing generated is left unstaged');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('a current generated document leaves the merge unchanged [B3,C7]', { timeout: 120000 }, () => { // budget: one real archive extraction, one generator run and one no-op check.
  const dir = temporaryRepository();
  try {
    const regenerated = spawnSync(process.execPath, ['docs/tools/update-docs.js'], { cwd: dir, env: cleanGitEnvironment(), encoding: 'utf8', timeout: 60000 });
    assert.equal(regenerated.status, 0, regenerated.stderr);
    if (git(dir, 'status', '--porcelain')) {
      git(dir, 'add', '-A');
      git(dir, 'commit', '-q', '-m', 'docs: regenerate shared documentation');
    }
    const merge = git(dir, 'rev-parse', 'HEAD');
    const before = readFileSync(join(dir, 'apps', 'cli', 'src/logic/help/additions.js'), 'utf8');
    amendLandingEngines(dir);
    assert.equal(git(dir, 'rev-parse', 'HEAD'), merge, 'a current merge is not amended');
    assert.equal(readFileSync(join(dir, 'apps', 'cli', 'src/logic/help/additions.js'), 'utf8'), before, 'current documentation keeps its bytes');
    assert.equal(git(dir, 'status', '--porcelain'), '', 'a current merge leaves the tree clean');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
